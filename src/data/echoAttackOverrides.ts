import type { AttackType, DamageElement, ScalingStat } from "../types/game";

/**
 * 에코 어빌리티 피해를 손으로 고쳐 적는 곳.
 *
 * src/data/echoAttacks.json은 원문을 기계로 훑어 만든 것이라
 * (`node scripts/build-echo-attacks.mjs`) 다시 돌리면 통째로 덮어써진다.
 * 사람이 읽어야 알 수 있는 것 — 어느 타격이 실제로 들어가는지, 갈라지는 조건이 있는지,
 * 어떤 피해 분류로 판정되는지 — 는 전부 이 파일에 둔다. 여기 적힌 에코는
 * 자동 추출분을 버리고 이 정의를 그대로 쓴다.
 *
 * 손보는 순서
 *   1) 에코 데이터 확인 탭(또는 echoAttacks.json의 review·text)에서 원문을 읽는다
 *   2) 실제로 한 번 쓸 때 들어가는 타격만 골라 attacks에 적는다
 *   3) 갈래가 여러 개면(짧게/길게, 회차별) 갈래마다 attacks를 하나씩 만든다
 *      — 계산 화면에서 실제로 쓴 것만 골라 담게 된다
 */

export interface EchoAttackDef {
  /** 공격 팔레트와 루틴에 뜨는 이름. 에코 이름은 앞에 자동으로 붙지 않는다. */
  name: string;
  element: DamageElement;
  scalingStat: ScalingStat;
  /** 타격별 계수(소수). 3단 100.56%면 [1.0056, 1.0056, 1.0056]. */
  hits: number[];
  /** 계수와 무관하게 더해지는 깡피해(「48.00%+96」의 96). 없으면 생략. */
  fixedDamage?: number;
  /**
   * 이 피해가 에코 피해가 아닌 다른 분류로 판정될 때.
   * 「폐기물로 인한 피해는 캐릭터의 반주 스킬 피해로 간주된다」 같은 문장이 근거다.
   * 생략하면 에코 피해(echoDamageBonus)로 본다.
   */
  damageBonusType?: AttackType;
  /**
   * **이 캐릭터가 꼈을 때만** 팔레트에 뜨는 갈래. 캐릭터 id 목록이며 생략하면 누구에게나 뜬다.
   *
   * 「루시에게 장착 시, 에코 어빌리티가 다음과 같이 대체된다」처럼 낀 사람에 따라
   * 어빌리티가 통째로 갈리는 에코가 있다. 갈래를 다 띄워 놓고 사람이 고르게 하면
   * 남의 것을 잘못 담기 쉬워서, 아예 그 캐릭터에게만 보이게 한다.
   */
  onlyCharacters?: string[];
  /** 위와 반대 — 이 캐릭터들일 때는 **빼는** 갈래. 「그 외에는 기본형」을 적을 때 쓴다. */
  exceptCharacters?: string[];
}

export interface EchoAttackOverride {
  /** 왜 손으로 고쳤는지. 화면에 그대로 뜬다. */
  note: string;
  attacks: EchoAttackDef[];
}

